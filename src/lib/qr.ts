/**
 * Tiny dependency-free QR Code encoder (byte mode, versions 1–40, auto mask).
 * Ported in spirit from Project Nayuki's reference implementation (MIT).
 * Used for the landing QR and the Pay-me poster so no third-party QR API
 * ever sees our URLs and the code works offline.
 */

export type QrEcl = 'L' | 'M' | 'Q' | 'H';
export interface QrMatrix {
  version: number;
  size: number;
  /** modules[y][x] — true = dark */
  modules: boolean[][];
}

const ECL_INDEX: Record<QrEcl, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECL_FORMAT: Record<QrEcl, number> = { L: 1, M: 0, Q: 3, H: 2 };

